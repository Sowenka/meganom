function breadcrumbs(items) {
  return {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: items.map((it, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      name: it.name,
      item: it.url,
    })),
  };
}

/** Строит массив JSON-LD блоков для маршрута */
function buildJsonLd(route, metadata, canonicalUrl) {
  const blocks = [];

  if (route === '/') {
    blocks.push({ '@context': 'https://schema.org', ...ORG_BASE, description: metadata.description });
  } else if (route === '/about' || route === '/contacts') {
    blocks.push({ '@context': 'https://schema.org', ...ORG_BASE, description: metadata.description, mainEntityOfPage: canonicalUrl });
    blocks.push(breadcrumbs([
      { name: 'Главная', url: SITE_URL + '/' },
      { name: route === '/about' ? 'О нас' : 'Контакты', url: canonicalUrl },
    ]));
  } else if (route === '/faq') {
    const faq = extractFaqItems(metadata.staticBody || '');
    if (faq.length) {
      blocks.push({ '@context': 'https://schema.org', '@type': 'FAQPage', mainEntity: faq });
    }
    blocks.push(breadcrumbs([
      { name: 'Главная', url: SITE_URL + '/' },
      { name: 'Вопросы и ответы', url: canonicalUrl },
    ]));
  } else if (route === '/rooms') {
    blocks.push(breadcrumbs([
      { name: 'Главная', url: SITE_URL + '/' },
      { name: 'Номера', url: canonicalUrl },
    ]));
  } else if (route === '/booking' || route === '/gallery') {
    const name = route === '/booking' ? 'Бронирование' : 'Фотогалерея';
    blocks.push(breadcrumbs([
      { name: 'Главная', url: SITE_URL + '/' },
      { name, url: canonicalUrl },
    ]));
  } else if (route === '/privacy' || route === '/terms' || route === '/consent') {
    const names = { '/privacy': 'Политика конфиденциальности', '/terms': 'Пользовательское соглашение', '/consent': 'Согласие на обработку персональных данных' };
    blocks.push(breadcrumbs([
      { name: 'Главная', url: SITE_URL + '/' },
      { name: names[route], url: canonicalUrl },
    ]));
  } else if (route.startsWith('/rooms/')) {
    blocks.push({
      '@context': 'https://schema.org',
      '@type': 'Accommodation',
      name: metadata.title.split(' | ')[0],
      description: metadata.description,
      image: metadata.ogImage,
      url: canonicalUrl,
      containedInPlace: { '@type': 'LodgingBusiness', name: SITE_NAME, url: SITE_URL },
    });
    blocks.push(breadcrumbs([
      { name: 'Главная', url: SITE_URL + '/' },
      { name: 'Номера', url: SITE_URL + '/rooms' },
      { name: metadata.title.split(' | ')[0], url: canonicalUrl },
    ]));
  }

  return blocks;
}

/** Заменяет SEO-теги в <head>. canonicalUrl = null - без canonical/og:url (страница 404). */
function injectMeta(html, { title, description, ogImage, noindex }, canonicalUrl, jsonLd) {
  html = html.replace(/<title>[^<]*<\/title>/, `<title>${title}</title>`);

  html = html.replace(
    /<meta\s+name="description"\s+content="[^"]*"\s*\/?>/,
    `<meta name="description" content="${description}">`,
  );

  html = html.replace(
    /<meta\s+property="og:title"\s+content="[^"]*"\s*\/?>/,
    `<meta property="og:title" content="${title}">`,
  );

  html = html.replace(
    /<meta\s+property="og:description"\s+content="[^"]*"\s*\/?>/,
    `<meta property="og:description" content="${description}">`,
  );

  html = html.replace(
    /<meta\s+property="og:url"\s+content="[^"]*"\s*\/?>/,
    canonicalUrl ? `<meta property="og:url" content="${canonicalUrl}">` : '',
  );

  html = html.replace(
    /<meta\s+property="og:image"\s+content="[^"]*"\s*\/?>/,
    `<meta property="og:image" content="${ogImage}">`,
  );

  // noindex для страниц, которые не должны индексироваться (юридические документы, 404)
  if (noindex) {
    if (!html.includes('name="robots"')) {
      html = html.replace(
        /(<\/head>)/,
        `  <meta name="robots" content="noindex, nofollow">\n$1`,
      );
    } else {
      html = html.replace(
        /<meta\s+name="robots"\s+content="[^"]*"\s*\/?>/,
        `<meta name="robots" content="noindex, nofollow">`,
      );
    }
  }

  // canonical - в index.html его нет (ставится JS), добавляем статически
  if (canonicalUrl) {
    if (!html.includes('rel="canonical"')) {
      html = html.replace(
        /(<\/head>)/,
        `  <link rel="canonical" href="${canonicalUrl}">\n$1`,
      );
    } else {
      html = html.replace(
        /<link\s+rel="canonical"\s+href="[^"]*"\s*\/?>/,
        `<link rel="canonical" href="${canonicalUrl}">`,
      );
    }
  }

  // JSON-LD - инжектим перед </head> для краулеров (Google/Yandex)
  if (jsonLd && jsonLd.length) {
    const ldTags = jsonLd
      .map((b) => `<script type="application/ld+json">${JSON.stringify(b)}</script>`)
      .join('\n  ');
    html = html.replace(/(<\/head>)/, `  ${ldTags}\n$1`);
  }

  return html;
}

/** Кладёт разметку внутрь <div id="root">. */
function injectRoot(html, inner) {
  return html.replace('<div id="root"></div>', `<div id="root">${inner}</div>`);
}

/** Создаёт директорию и пишет index.html */
function writeRoute(distDir, routePath, html) {
  if (routePath === '/') {
    writeFileSync(join(distDir, 'index.html'), html, 'utf-8');
    return 'dist/index.html';
  }
  const dir = join(distDir, ...routePath.slice(1).split('/'));
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
  const outputPath = join(dir, 'index.html');
  writeFileSync(outputPath, html, 'utf-8');
  return outputPath.replace(/\\/g, '/');
}

const NOT_FOUND_META = {
  title: `Страница не найдена | ${SITE_NAME}`,
  description: 'Такой страницы на сайте нет. Перейдите на главную, к номерам или контактам гостиницы «Меганом».',
  ogImage: DEFAULT_OG_IMAGE,
  noindex: true,
};
// Любой адрес вне маршрутов: роутер покажет NotFound
const NOT_FOUND_PROBE_URL = '/__prerender-not-found__';

async function launchChromium() {
  const { chromium } = await import('@playwright/test');
  try {
    return await chromium.launch();
  } catch {
    // Бандл Chromium от Playwright не скачан - пробуем установленный Google Chrome
    try {
      return await chromium.launch({ channel: 'chrome' });
    } catch (err) {
      throw new Error(
        '[seo-prerender] Не найден браузер для снимков страниц. ' +
          'Выполните `npx playwright install chromium` или установите Google Chrome. ' +
          `Причина: ${err.message.split('\n')[0]}`,
      );
    }
  }
}

/**
 * Открывает собранный сайт в headless-браузере и снимает готовую разметку #root.
 *
 * Зачем: Яндекс плохо исполняет JS и оценивает страницу по исходному HTML.
 * Раньше там лежал только текст, скрытый через clip:rect - для робота это
 * скрытый текст и пустая страница, отсюда статус "малоценная". Теперь в HTML
 * та же видимая разметка, что видит посетитель.
 */
async function snapshotPages(distDir, urls) {
  const { preview } = await import('vite');
  const server = await preview({
    configFile: false,
    logLevel: 'silent',
    build: { outDir: distDir },
    preview: { host: '127.0.0.1', port: 4179, strictPort: false },
  });
  const origin = server.resolvedUrls.local[0].replace(/\/$/, '');
  const browser = await launchChromium();

  try {
    const context = await browser.newContext({ viewport: { width: 1280, height: 800 }, locale: 'ru-RU' });
    // В снимок не должны попадать живые данные (погода, API) и сторонние скрипты
    await context.route(
      (url) => url.origin !== origin || url.pathname.startsWith('/api/'),
      (route) => route.abort(),
    );
    await context.addInitScript(() => {
      // Выбор по cookie уже "сделан" - баннер согласия не попадает в HTML каждой страницы.
      // try: в iframe с заблокированным адресом localStorage недоступен.
      try {
        localStorage.setItem(
          'meganom_cookie_consent_v1',
          JSON.stringify({ analytics: false, decidedAt: '2026-01-01T00:00:00.000Z' }),
        );
      } catch {
        // не страница сайта
      }
      // Все элементы "в зоне видимости": whileInView-анимации и счётчики доходят до
      // финального состояния, иначе текст ниже первого экрана остаётся с opacity:0.
      window.IntersectionObserver = class {
        constructor(callback) {
          this.callback = callback;
        }
        observe(target) {
          setTimeout(() => {
            const rect = target.getBoundingClientRect();
            this.callback(
              [{ target, isIntersecting: true, intersectionRatio: 1, boundingClientRect: rect, intersectionRect: rect, rootBounds: null, time: performance.now() }],
              this,
            );
          }, 0);
        }
        unobserve() {}
        disconnect() {}
        takeRecords() {
          return [];
        }
      };
    });

    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', (err) => errors.push(err.message));

    const result = {};
    for (const url of urls) {
      await page.goto(origin + url, { waitUntil: 'networkidle' });
      await page.waitForFunction(
        () => document.querySelector('#root')?.childElementCount > 0 && !document.querySelector('#root .animate-spin'),
      );
      // Входные анимации framer-motion и счётчики на главной (до ~1.4 с)
      await page.waitForTimeout(2200);

      const snap = await page.evaluate(() => {
        const root = document.getElementById('root');
        // Текст, оставшийся невидимым из-за незавершённой анимации (inline opacity:0)
        const hidden = [...root.querySelectorAll('[style*="opacity: 0"]')]
          .map((el) => el.textContent.trim())
          .filter(Boolean)
          .map((t) => t.slice(0, 60));
        return { html: root.innerHTML, textLength: root.innerText.length, hidden };
      });

      if (snap.html.includes(origin)) {
        throw new Error(`[seo-prerender] ${url}: в разметку попал адрес превью-сервера ${origin}`);
      }
      if (snap.hidden.length) {
        console.warn(`  WARN ${url}: скрытый текст в снимке: ${snap.hidden.join(' | ')}`);
      }
      result[url] = snap;
    }

    if (errors.length) {
      throw new Error(`[seo-prerender] Ошибки JS при снятии снимков: ${errors.join('; ')}`);
    }
    return result;
  } finally {
    await browser.close();
    await server.close();
  }
}

export default function seoPrerender() {
  return {
    name: 'vite-plugin-seo-prerender',
    apply: 'build',

    async closeBundle() {
      const distDir = 'dist';
      const indexPath = join(distDir, 'index.html');

      if (!existsSync(indexPath)) {
        console.warn('\n[seo-prerender] dist/index.html не найден\n');
        return;
      }

      console.log('\n[SEO pre-render] Генерация статических HTML...\n');

      const baseHtml = readFileSync(indexPath, 'utf-8');

      // 1. Страницы с SEO-тегами и пустым #root: с них же снимаются снимки
      const pages = [];
      for (const [route, metadata] of Object.entries(routeMetadata)) {
        const canonicalUrl = `${SITE_URL}${route === '/' ? '' : route}`;
        const jsonLd = metadata.noindex ? [] : buildJsonLd(route, metadata, canonicalUrl);
        pages.push({ route, metadata, html: injectMeta(baseHtml, metadata, canonicalUrl, jsonLd) });
      }
      for (const [slug, metadata] of Object.entries(roomMetadata)) {
        const route = `/rooms/${slug}`;
        const canonicalUrl = `${SITE_URL}${route}`;
        const jsonLd = buildJsonLd(route, metadata, canonicalUrl);
        pages.push({ route, metadata, html: injectMeta(baseHtml, metadata, canonicalUrl, jsonLd) });
      }
      const notFoundHtml = injectMeta(baseHtml, NOT_FOUND_META, null, []);
      for (const p of pages) writeRoute(distDir, p.route, p.html);
      // Оболочка для клиентских маршрутов (/auth, /profile, /admin - см. .htaccess):
      // пустой #root, иначе до загрузки JS на них мелькал бы снимок главной.
      writeFileSync(join(distDir, 'spa.html'), injectMeta(baseHtml, { ...NOT_FOUND_META, title: SITE_NAME, description: routeMetadata['/'].description }, null, []), 'utf-8');

      // 2. Снимки отрисованных страниц -> видимая разметка в #root
      if (process.env.SKIP_PRERENDER) {
        console.warn('  SKIP_PRERENDER: снимки не сняты, в #root только скрытый текст. Такой билд НЕ деплоить.');
        for (const p of pages) {
          if (!p.metadata.staticBody) continue;
          const hiddenBody = `<div style="position:absolute;overflow:hidden;clip:rect(0 0 0 0);width:1px;height:1px;white-space:nowrap;">${p.metadata.staticBody}</div>`;
          writeRoute(distDir, p.route, injectRoot(p.html, hiddenBody));
        }
        writeFileSync(join(distDir, '404.html'), notFoundHtml, 'utf-8');
        return;
      }

      const snapshots = await snapshotPages(distDir, [...pages.map((p) => p.route), NOT_FOUND_PROBE_URL]);
      for (const p of pages) {
        const snap = snapshots[p.route];
        const out = writeRoute(distDir, p.route, injectRoot(p.html, snap.html));
        console.log(`  OK ${p.route.padEnd(28)} ${String(snap.textLength).padStart(6)} симв. -> ${out}`);
      }
      const notFound = snapshots[NOT_FOUND_PROBE_URL];
      writeFileSync(join(distDir, '404.html'), injectRoot(notFoundHtml, notFound.html), 'utf-8');
      console.log(`  OK ${'404'.padEnd(28)} ${String(notFound.textLength).padStart(6)} симв. -> dist/404.html`);

      console.log(`\n[SEO pre-render] Готово: ${pages.length} страниц + 404\n`);
    },
  };
}
