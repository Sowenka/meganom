/** Парсит FAQ из staticBody (dl/dt/dd) для FAQPage schema */
function extractFaqItems(staticBody) {
  const items = [];
  const re = /<dt>([^<]+)<\/dt>\s*<dd>([^<]+)<\/dd>/g;
  let m;
  while ((m = re.exec(staticBody)) !== null) {
    items.push({
      '@type': 'Question',
      name: m[1].trim(),
      acceptedAnswer: { '@type': 'Answer', text: m[2].trim() },
    });
  }
  return items;
}

